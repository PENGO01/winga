"""v2.23: stale order is forgotten, copy/labels, gold tab, Mwonekano in settings, back swipe."""
from playwright.sync_api import sync_playwright
import hook
B="http://localhost:8765/beta/"
R=[]
def ok(n,c,x=""):
    R.append((n,bool(c))); print(("PASS " if c else "FAIL ")+n+(" · "+str(x) if x else ""))
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844},has_touch=True,is_mobile=True)
    hook.install(ctx,B); pg=ctx.new_page(); errs=[]
    pg.on("pageerror",lambda e: errs.append(str(e)))
    # a code the server has never heard of, left behind in the phone's storage
    pg.add_init_script("try{if(!localStorage.getItem('__seeded')){localStorage.setItem('niagize.myorders',JSON.stringify(['NK-XDF6K']));localStorage.setItem('niagize.hist',JSON.stringify([{code:'NK-XDF6K',status:'new',created_at:new Date().toISOString(),items:[{name:'Classic Coat',qty:1,price:60000}]}]));localStorage.setItem('__seeded','1');}}catch(e){}")
    pg.goto(B+"?demo"); pg.wait_for_timeout(2500)
    pg.evaluate("document.querySelectorAll('.scrim [data-act=back],.scrim .close').forEach(e=>e.click())")
    pg.click("nav.tabs button[data-tab=me]"); pg.wait_for_timeout(2500)
    mine=pg.evaluate("JSON.parse(localStorage.getItem('niagize.myorders')||'[]')")
    ok("C1 unknown cached order is forgotten",'NK-XDF6K' not in mine,mine)
    ok("C2 it no longer shows on Mimi","NK-XDF6K" not in pg.inner_text("body"))
    ok("C3 Mwonekano row gone from the profile page",pg.locator(".mprefs").count()==0)
    ok("C4 guest has a gear",pg.locator(".ghero .gear").count()==1)
    pg.click(".ghero .gear"); pg.wait_for_timeout(500)
    sheet=pg.inner_text("#sheetRoot")
    ok("C5 settings has the appearance row, no sign-out for a guest","Mwonekano" in sheet and "Toka" not in sheet,sheet[:120])
    pg.go_back(); pg.wait_for_timeout(500)
    ok("C6 back gesture closes the settings sheet",pg.locator("#sheetRoot .sheet").count()==0 and "/beta/" in pg.url)
    pg.click("nav.tabs button[data-tab=cart]"); pg.wait_for_timeout(500)
    ok("C7 empty cart text","Hakuna kitu kwenye kapu" in pg.inner_text("body"))
    pg.click("nav.tabs button[data-tab=home]"); pg.wait_for_timeout(800)
    col=pg.evaluate("getComputedStyle(document.querySelector('nav.tabs button[aria-current=page]')).color")
    ok("C8 active tab is gold",col.replace(" ","") in("rgb(255,198,45)",),col)
    pg.locator("[data-act=open]").first.click(); pg.wait_for_timeout(700)
    bar=pg.inner_text(".actbar")
    ok("C9 product buttons: Tuulize · Weka kapuni · Agiza chap",all(x in bar for x in("Tuulize","Weka kapuni","Agiza chap")),bar.replace("\n"," | "))
    ok("C10 order button has an arrow",pg.locator(".actbar .btn.primary svg").count()==1)
    pg.go_back(); pg.wait_for_timeout(500)
    ok("C11 back swipe closes the product page",pg.locator("#sheetRoot .sheet").count()==0)
    pg.locator("[data-act=open]").first.click(); pg.wait_for_timeout(600)
    pg.click(".actbar .btn.primary"); pg.wait_for_timeout(500)
    pg.go_back(); pg.wait_for_timeout(500)
    ok("C12 two levels deep: one swipe goes back one level",pg.locator("#sheetRoot .sheet").count()==1)
    pg.go_back(); pg.wait_for_timeout(400)
    pg.locator(".pc .fav").first.click(); pg.wait_for_timeout(400)
    ok("F1 tap saves a product (stored on the phone)",pg.evaluate("JSON.parse(localStorage.getItem('niagize.favs')||'[]').length")==1)
    ok("F2 the mark turns on",pg.locator(".pc .fav.on").count()==1)
    pg.reload(); pg.wait_for_timeout(2200)
    pg.evaluate("document.querySelectorAll('.scrim [data-act=back],.scrim .close').forEach(e=>e.click())")
    ok("F3 still saved after reload",pg.locator(".pc .fav.on").count()==1)
    pg.click("nav.tabs button[data-tab=me]"); pg.wait_for_timeout(600)
    pg.click(".tl[data-act=favs]"); pg.wait_for_timeout(500)
    ok("F4 Hifadhi list shows it",pg.locator("#sheetRoot .pc").count()==1)
    pg.locator("#sheetRoot .fav").first.click(); pg.wait_for_timeout(400)
    ok("F5 removing empties the list",pg.locator("#sheetRoot .pc").count()==0 and "Bado hujahifadhi" in pg.inner_text("#sheetRoot"))
    ok("C-errors none",not errs,errs)
    b.close()
n=sum(1 for _,c in R if c); print(f"{n} / {len(R)}")
